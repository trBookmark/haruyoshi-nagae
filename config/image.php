<?php

/**
 * 画像関連設定
 */
return [

  /*
  |--------------------------------------------------------------------------
  | CDN URL
  |--------------------------------------------------------------------------
  |
  | 画像URLのベースURL
  | CDN移行前は null のまま（Storage::url() が使われる）
  | CDN移行後は .env に CDN_URL を設定し、キャッシュをクリアすることで全画像のURLが切り替わる
  |
  */
  'cdn_url' => env('CDN_URL', null),

  /*
  |--------------------------------------------------------------------------
  | 画像リサイズ設定
  |--------------------------------------------------------------------------
  |
  | 各サイズの長辺基準ピクセル数を定義
  | リサイズ方式：縦横比維持・長辺基準・拡大なし
  | GIFアニメーションはリサイズ対象外（全サイズそのまま保存）
  |
  | Retina（2x）対応のため、CSS上の表示サイズの2倍を基準とする：
  |   thumb : 190px 表示 → 400px
  |   medium: 280px 表示 → 600px
  |   large : フル表示   → 1920px
  |
  */
  'resize' => [
    'large'  => 1920,
    'medium' => 600,
    'thumb'  => 400,
  ],

  /*
  |--------------------------------------------------------------------------
  | 画像品質設定
  |--------------------------------------------------------------------------
  |
  | Intervention Image v3 によるエンコード時の品質パラメータ
  |
  | jpeg: 1〜100（高いほど高画質・大容量）
  |
  */
  'quality' => [
    'jpeg' => 90,
  ],

  /*
  |--------------------------------------------------------------------------
  | アップロード許可 MIME タイプ
  |--------------------------------------------------------------------------
  |
  | 画像アップロード時に許可する MIME タイプの一覧
  | FormRequest と ImageUploadService の両方から参照される
  | 将来 WebP 等を追加する場合はここに追記する
  |
  */
  'allowed_mime_types' => ['image/jpeg', 'image/png', 'image/gif'],

  /*
  |--------------------------------------------------------------------------
  | アップロードサイズ上限
  |--------------------------------------------------------------------------
  |
  | Filament FileUpload の ->maxSize() に渡す値（KB単位）
  | php.ini の upload_max_filesize: 2048M に合わせて 2097152 KB（2048MB）
  |
  */
  'upload_max_size_kb' => 2097152,

  /*
  |--------------------------------------------------------------------------
  | デフォルト画像設定
  |--------------------------------------------------------------------------
  |
  | サムネイルが見つからない場合にデフォルトで表示するための画像ファイル名
  | png推奨、GIFアニメは非推奨（リサイズなしで保存されるため）
  | 使用する場合、resize設定に従った3サイズのno-image.pngを用意し、以下に配置する：
  | storage/app/public/images/large/no-image.png
  | storage/app/public/images/medium/no-image.png
  | storage/app/public/images/thumb/no-image.png
  |
  */
  'no_image_filename' => 'no-image.png',

  /*
  |--------------------------------------------------------------------------
  | 管理画面ユーザーアバター設定
  |--------------------------------------------------------------------------
  */
  'avatar' => [
    'disk'                => 'public',
    'accepted_mime_types' => ['image/png', 'image/jpeg'],
    'max_size_kb'         => 3072, // 3MB
    'directory'           => 'avatars',
  ],

  /*
  |--------------------------------------------------------------------------
  | 画像保存先ディスク設定
  |--------------------------------------------------------------------------
  |
  | original : 非公開（バックアップ・再生成用）
  | resized  : 公開（large / medium / thumb 共通）
  |
  */
  'disks' => [
    'original' => 'local',  // storage/app/private/
    'resized'  => 'public', // storage/app/public/
  ],

  /*
  |--------------------------------------------------------------------------
  | ExifTool 設定
  |--------------------------------------------------------------------------
  |
  | ExifTool のパス
  | ローカル（Sail）では which exiftool の結果を設定
  |
  */
  'exiftool' => [
    'binary'   => env('EXIFTOOL_BINARY'),   // 必須。未設定時は ExifCleaner が例外をスロー
    'perl5lib' => env('EXIFTOOL_PERL5LIB', ''), // ローカル（apt インストール）では不要
  ],

];
